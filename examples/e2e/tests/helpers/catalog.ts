export type ExampleKind =
  | "datachannel"
  | "media-inbound"
  | "media-record"
  | "close-dc"
  | "close-pc"
  | "ice-restart"
  | "process-exit"
  | "node-gst";

export type ClientKind = "babel" | "vite" | "none";

export type BinaryNeed = "gst" | "ffmpeg";

export type CatalogEntry = {
  id: string;
  /** Catalog group for tests and AGENTS.md */
  group: "browser" | "ffmpeg-gstreamer";
  node: string[];
  html?: string;
  port: number;
  client: ClientKind;
  kind: ExampleKind;
  binary?: BinaryNeed;
  /** gst/ffmpeg を spawn するポート。binary がなくても生存 Assert 対象になる */
  extraGstPorts?: number[];
  click?: string;
  fileInput?: "webm" | "mp4";
  skipIfNoAv1?: boolean;
  /** Where media is asserted. recvonly/codec demos send browser→werift. */
  inbound?: "browser" | "werift";
  /** Server log markers for each werift-side inbound simulcast track. */
  weriftRtpLogs?: string[];
  /** UDP port the example forwards RTP to; harness binds and counts packets */
  rtpForwardPort?: number;
  env?: Record<string, string>;
  waitLog?: string | RegExp | false;
  expectExit?: number;
  outputGlob?: string;
  /** Seconds to wait after connect before asserting a recording file */
  recordWaitMs?: number;
  /** Validate the resulting container with ffprobe. */
  outputContainer?: "webm" | "mp4";
  /** Stop a long-running example after its output has been observed. */
  stopAfterOutput?: boolean;
  /** Log marker proving RTP reached the recording pipeline. */
  rtpLog?: string | RegExp;
};

export type ExcludedExample = {
  path: string;
  reason: string;
};

