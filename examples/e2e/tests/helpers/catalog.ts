export function catalogById(id: string) {
  const entry = catalog.find((item) => item.id === id);
  if (!entry) {
    throw new Error(`unknown catalog id: ${id}`);
  }
  return entry;
}

export function catalogByGroup(group: CatalogEntry["group"]) {
  return catalog.filter((item) => item.group === group);
}
